    // 1. Method mengambil jenis peserta
    private String getJenisPeserta() {
        if (rbMahasiswa.isSelected()) {
            return "Mahasiswa";
        }
        if (rbUmum.isSelected()) {
            return "Umum";
        }
        return "";
    }

    // 2. Method menentukan biaya dasar dengan Switch Statement (Java 8 compatible)
private double hitungBiayaDasar(String kursus) {
    double biaya = 0;
    
    switch (kursus) {
        case "Java Desktop":
            biaya = 500_000;
            break;
        case "Data Science":
            biaya = 650_000;
            break;
        case "Web Programming":
            biaya = 450_000;
            break;
        case "UI/UX Design":
            biaya = 400_000;
            break;
        default:
            biaya = 0;
            break;
    }
    
    return biaya;
}

    // 3. Method menghitung biaya checkbox fasilitas
    private double hitungBiayaFasilitas() {
        double total = 0;
        if (cbModul.isSelected()) {
            total += 50_000;
        }
        if (cbSertifikat.isSelected()) {
            total += 75_000;
        }
        if (cbRekaman.isSelected()) {
            total += 40_000;
        }
        return total;
    }

    // 4. Method Array + Loop untuk merangkum fasilitas
    private String buatRingkasanFasilitas() {
        String[] fasilitasDipilih = new String[3];
        int jumlah = 0;

        if (cbModul.isSelected()) {
            fasilitasDipilih[jumlah] = "Modul Cetak";
            jumlah++;
        }
        if (cbSertifikat.isSelected()) {
            fasilitasDipilih[jumlah] = "Sertifikat";
            jumlah++;
        }
        if (cbRekaman.isSelected()) {
            fasilitasDipilih[jumlah] = "Akses Rekaman";
            jumlah++;
        }

        if (jumlah == 0) {
            return "Tidak ada fasilitas tambahan\n";
        }

        StringBuilder hasil = new StringBuilder();
        for (int i = 0; i < jumlah; i++) {
            hasil.append("- ").append(fasilitasDipilih[i]).append("\n");
        }
        return hasil.toString();
    }

    // 5. Method Validasi Input
    private boolean validasiInput() {
        String nama = txtNama.getText().trim();
        String kode = new String(txtKodeAkses.getPassword());

        if (nama.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Nama peserta wajib diisi.", "Validasi", javax.swing.JOptionPane.WARNING_MESSAGE);
            txtNama.requestFocus();
            return false;
        }

        if (!kode.equals("PBO2026")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Kode akses demo salah.", "Validasi", javax.swing.JOptionPane.WARNING_MESSAGE);
            txtKodeAkses.requestFocus();
            return false;
        }

        if (!rbMahasiswa.isSelected() && !rbUmum.isSelected()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih jenis peserta.", "Validasi", javax.swing.JOptionPane.WARNING_MESSAGE);
            return false;
        }

        if (cmbKursus.getSelectedIndex() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih kursus terlebih dahulu.", "Validasi", javax.swing.JOptionPane.WARNING_MESSAGE);
            return false;
        }

        return true;
    }

    // 6. Method Reset Form
    private void resetForm() {
        txtNama.setText("");
        txtKodeAkses.setText("");
        groupJenis.clearSelection();
        cmbKursus.setSelectedIndex(0);
        cbModul.setSelected(false);
        cbSertifikat.setSelected(false);
        cbRekaman.setSelected(false);
        txtRingkasan.setText("");
        txtNama.requestFocus();
    }    
    
